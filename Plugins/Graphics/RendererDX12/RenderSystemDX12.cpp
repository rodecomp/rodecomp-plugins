#include "RenderSystemDX12.h"

#include "RendererDX12.h"

#include "Render/DX7/RenderSystemDX7.h"

#include <new>

RenderSystemDX12::~RenderSystemDX12() {
  this->RenderSystemDX12::Close();
}

std::int32_t RenderSystemDX12::Backend() {
  return 3;
}

HRESULT RenderSystemDX12::Initialize(HWND window) {
  if (!window) {
    return E_INVALIDARG;
  }

  // DeviceOwnerDX9::CreateDevice: the configured mode in fullscreen, the client area in a window.
  this->m_fullscreen = g_configuredFullscreen != 0;
  UINT width = g_configuredScreenWidth;
  UINT height = g_configuredScreenHeight;
  if (!this->m_fullscreen) {
    RECT rectangle;
    GetClientRect(window, &rectangle);
    width = rectangle.right - rectangle.left;
    height = rectangle.bottom - rectangle.top;
  }

  const HRESULT result = this->m_device.Initialize(window, width, height, g_configuredDeviceName);
  if (FAILED(result)) {
    this->m_device.Close();
    return result;
  }

  this->TestDevice();
  SetActiveDeviceDX12(&this->m_device);
  return S_OK;
}

HRESULT RenderSystemDX12::Close() {
  SetActiveDeviceDX12(nullptr);
  this->m_defaultTexture.reset();
  this->m_backBuffer = nullptr;
  this->m_device.Close();
  return S_OK;
}

// CRenderSystemDX9 answers presentation.Windowed == 0.
bool RenderSystemDX12::IsWindowed() {
  return this->m_fullscreen;
}

std::uint32_t RenderSystemDX12::Width() {
  return this->m_device.width;
}

std::uint32_t RenderSystemDX12::Height() {
  return this->m_device.height;
}

CRenderer* RenderSystemDX12::CreateRenderer() {
  auto* renderer = new CRendererDX12(this->m_device);
  renderer->SetSize(this->RenderSystemDX12::Width(), this->RenderSystemDX12::Height());
  return renderer;
}

void RenderSystemDX12::DestroyRenderer(CRenderer* renderer) {
  delete renderer;
}

CSurface* RenderSystemDX12::CreateSurface(std::uint32_t width, std::uint32_t height) {
  return new (std::nothrow) CSurfaceDX12(this->m_device, width, height);
}

CTexture* RenderSystemDX12::CreateTexture(std::uint32_t width, std::uint32_t height, std::int32_t format, bool dynamic, bool renderTarget) {
  return new (std::nothrow) CTextureDX12(this->m_device, width, height, format, dynamic, renderTarget);
}

CSurface* RenderSystemDX12::CreateSurfaceOrTexture(std::uint32_t width, std::uint32_t height) {
  if (width <= D3D12_REQ_TEXTURE2D_U_OR_V_DIMENSION && height <= D3D12_REQ_TEXTURE2D_U_OR_V_DIMENSION) {
    return this->RenderSystemDX12::CreateTexture(width, height, TextureFormat::A1R5G5B5, false, false);
  }

  return this->RenderSystemDX12::CreateSurface(width, height);
}

CTexture* RenderSystemDX12::BackBufferTexture() {
  if (!this->m_defaultTexture) {
    this->m_defaultTexture = std::make_unique<CTextureDX12>(this->m_device);
  }

  return this->m_defaultTexture.get();
}

std::shared_ptr<CSurface> RenderSystemDX12::BackBufferSurface() {
  if (!this->m_backBuffer) {
    this->m_backBuffer = std::make_shared<CSurfaceDX12>(this->m_device);
  }

  return this->m_backBuffer;
}

