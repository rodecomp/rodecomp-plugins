HRESULT RenderSystemDX12::TestDevice() {
  if (this->m_fullscreen && this->m_device.window) {
    RECT rectangle;
    GetWindowRect(this->m_device.window, &rectangle);
    ClipCursor(&rectangle);
  }

  return S_OK;
}

HRESULT RenderSystemDX12::Present(bool) {
  return this->m_device.Present();
}
